"""`anci init` — wizard that generates a first anci.toml.

Best-effort build-output detection, always editable output. The conf-building
logic is a pure function (testable); the wizard just feeds it answers.
"""

from __future__ import annotations

import getpass
import re
import subprocess
import sys
from pathlib import Path

from .. import errors, ui, validate

DETECT_CANDIDATES = [
    "target/release/{name}",
    "target/debug/{name}",
    "dist/{name}",
    "build/{name}",
    "{name}",
    "{name}.py",
]


def detect_source(cwd: Path, name: str) -> str | None:
    for candidate in DETECT_CANDIDATES:
        p = cwd / candidate.format(name=name)
        if p.is_file():
            return f"./{candidate.format(name=name)}"
    return None


def detect_ssh_key() -> str | None:
    try:
        out = subprocess.run(
            ["ssh-add", "-L"], capture_output=True, text=True, timeout=5
        )
        if out.returncode == 0 and out.stdout.strip():
            return out.stdout.strip().splitlines()[0]
    except (OSError, subprocess.TimeoutExpired):
        pass
    for keyfile in ("id_ed25519.pub", "id_ecdsa.pub", "id_rsa.pub"):
        p = Path.home() / ".ssh" / keyfile
        if p.is_file():
            return p.read_text().strip()
    return None


def normalize_name(raw: str, fallback: str) -> str:
    name = re.sub(r"[^a-z0-9]+", "-", raw.lower()).strip("-")[:32].rstrip("-")
    return name if validate.NAME_RE.match(name) else fallback


def default_user() -> str:
    try:
        return normalize_name(getpass.getuser(), "you")
    except Exception:
        return "you"


def build_init_conf(*, name: str, source: str | None, ssh_key: str | None,
                    user: str = "you") -> str:
    key_line = ssh_key or f"ssh-ed25519 PASTE-YOUR-PUBLIC-KEY-HERE {user}@dev-machine"
    if source:
        source_line, source_note = source, ""
    else:
        source_line, source_note = f"./target/release/{name}", "    # TODO: build first"
    return f"""# generated by anci init — tweak freely (full format: external-docs/robots.md)

anci-version = '0.0.1'

[user.{user}]
ssh-pub-keys = '{key_line}'

[env.dev]
ip = '127.0.0.1'              # '127.0.0.1' = "the local box" (address is assigned for you)
access-users = ['{user}']
vm = {{ vcpus = 2, mem = '1gb', disk = '20gb' }}

[exe.{name}]
source = '{source_line}'{source_note}
"""


def init(cwd: Path | None = None) -> int:
    cwd = cwd or Path.cwd()
    target = cwd / "anci.toml"
    if target.exists():
        raise errors.ConfError("anci.toml already exists here — not touching it")
    if not sys.stdin.isatty():
        raise errors.ConfError(
            "anci init is interactive; run it in a terminal",
            try_="or copy the example conf: examples/guestbook/anci.toml in the ancisite repo",
        )

    u_default = default_user()
    user = input(f"your username [{u_default}]: ").strip() or u_default
    user = normalize_name(user, u_default)

    default_name = normalize_name(cwd.name, "app")
    name = normalize_name(input(f"app name [{default_name}]: "), default_name)

    detected = detect_source(cwd, name)
    if detected:
        source = input(f"app file [{detected}]: ").strip() or detected
    else:
        source = input(f"app file (path to your server binary) [./target/release/{name}]: ").strip()
        source = source or f"./target/release/{name}"

    key = detect_ssh_key()
    if key:
        print(f"  using ssh key: {ui.dim(key[:40] + '...')}")
    else:
        print(f"  {ui.yellow('note:')} no ssh key found — paste yours into anci.toml")

    target.write_text(build_init_conf(name=name, source=source, ssh_key=key, user=user))
    print(f"\n  wrote {ui.bold('anci.toml')}")
    print(f"\n  {ui.dim('next:')} build your app, then:")
    print(f"  {ui.bold('anci dev up')}")
    print(f"  {ui.bold(f'anci dev deploy {name}')}")
    return 0
